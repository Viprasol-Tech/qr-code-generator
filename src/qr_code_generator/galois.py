"""GF(256) arithmetic and Reed-Solomon error correction for QR codes.

The QR standard (ISO/IEC 18004) uses the Galois field GF(256) generated by the
primitive polynomial ``x^8 + x^4 + x^3 + x^2 + 1`` (0x11D). This module builds
the exponential/logarithm tables for that field and implements Reed-Solomon
error-correction codeword generation on top of them.

Part of QR Code Generator by Viprasol Tech Private Limited (https://viprasol.com).
"""

from __future__ import annotations

# Primitive polynomial used by QR codes: x^8 + x^4 + x^3 + x^2 + 1.
_PRIMITIVE = 0x11D


def _build_tables() -> tuple[list[int], list[int]]:
    """Build the GF(256) exponent and logarithm lookup tables.

    Returns a pair ``(exp, log)`` where ``exp[i]`` is ``alpha**i`` and
    ``log[x]`` is the discrete logarithm of ``x`` (base ``alpha``).
    """
    exp = [0] * 512
    log = [0] * 256
    value = 1
    for i in range(255):
        exp[i] = value
        log[value] = i
        value <<= 1
        if value & 0x100:
            value ^= _PRIMITIVE
    # Duplicate the table so multiplication can index without modulo.
    for i in range(255, 512):
        exp[i] = exp[i - 255]
    return exp, log


_EXP, _LOG = _build_tables()


def gf_mul(a: int, b: int) -> int:
    """Multiply two elements of GF(256)."""
    if a == 0 or b == 0:
        return 0
    return _EXP[_LOG[a] + _LOG[b]]


def gf_pow(a: int, power: int) -> int:
    """Raise a GF(256) element ``a`` to an integer ``power``."""
    if a == 0:
        return 0
    return _EXP[(_LOG[a] * power) % 255]


def _generator_poly(degree: int) -> list[int]:
    """Build the Reed-Solomon generator polynomial of the given degree.

    The polynomial is ``(x - alpha^0)(x - alpha^1)...(x - alpha^(degree-1))``
    expanded over GF(256), returned highest-degree coefficient first.
    """
    poly = [1]
    for i in range(degree):
        # Multiply the running polynomial by (x - alpha^i).
        new = [0] * (len(poly) + 1)
        factor = _EXP[i]
        for j, coeff in enumerate(poly):
            new[j] ^= coeff
            new[j + 1] ^= gf_mul(coeff, factor)
        poly = new
    return poly


def reed_solomon(data: list[int], ec_count: int) -> list[int]:
    """Compute ``ec_count`` Reed-Solomon error-correction codewords for ``data``.

    Args:
        data: The data codewords (each an integer 0-255).
        ec_count: The number of error-correction codewords to produce.

    Returns:
        The list of ``ec_count`` error-correction codewords.
    """
    generator = _generator_poly(ec_count)
    # Polynomial long division; the remainder is the EC codewords.
    remainder = list(data) + [0] * ec_count
    for i in range(len(data)):
        coeff = remainder[i]
        if coeff == 0:
            continue
        for j, g in enumerate(generator):
            remainder[i + j] ^= gf_mul(g, coeff)
    return remainder[len(data) :]
